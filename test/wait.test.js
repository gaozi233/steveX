const test = require('node:test')
const assert = require('node:assert/strict')
const { EventEmitter } = require('node:events')
const { handler } = require('../src/commands/actions/wait')

test('wait validates whole integers and cleans listeners on completion/disconnect/abort', async () => {
  const bot = new EventEmitter()
  for (const args of [['2abc'], ['2.5'], ['0'], ['-1'], ['Infinity'], ['9007199254740992'], ['2', 'extra']]) assert.equal((await handler(bot, args)).ok, false)
  const done = handler(bot, ['2'])
  bot.emit('physicsTick'); assert.equal(bot.listenerCount('physicsTick'), 1)
  bot.emit('physicsTick'); assert.ok((await done).ok)
  assert.equal(bot.listenerCount('end'), 0)
  const disconnected = handler(bot, ['2']); bot.emit('end')
  assert.equal((await disconnected).errorCode, 'DISCONNECTED')
  const controller = new AbortController()
  const aborted = handler(bot, ['2'], null, { signal: controller.signal })
  controller.abort(new Error('test stop'))
  const result = await aborted
  assert.equal(result.errorCode, 'CANCELLED')
  assert.match(result.error, /test stop/)
  assert.equal(bot.listenerCount('physicsTick'), 0)
  assert.equal(bot.listenerCount('end'), 0)
})
